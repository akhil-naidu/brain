/**
 * Build-time helper: if SNOWFLAKE_MCP_URL is set, write the generated
 * connection URL module so `eve build` bakes it into the Nitro bundle.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const mcpUrl = process.env.SNOWFLAKE_MCP_URL?.trim();
if (!mcpUrl) {
  console.log("[write-snowflake-compiled-url] SNOWFLAKE_MCP_URL unset; keeping placeholder");
  process.exit(0);
}
if (!URL.canParse(mcpUrl)) {
  console.error(`[write-snowflake-compiled-url] invalid SNOWFLAKE_MCP_URL: ${mcpUrl}`);
  process.exit(1);
}

const destination = join(process.cwd(), "agent", "lib", "snowflake-mcp-url.generated.ts");
mkdirSync(dirname(destination), { recursive: true });
writeFileSync(
  destination,
  `/**
 * Generated by Connections → Snowflake → Set up.
 * Eve compiles this string into the connection manifest — do not hand-edit.
 */
export const SNOWFLAKE_COMPILED_MCP_URL = ${JSON.stringify(mcpUrl)} as const;
`,
  "utf8",
);
console.log(`[write-snowflake-compiled-url] wrote ${destination}`);
